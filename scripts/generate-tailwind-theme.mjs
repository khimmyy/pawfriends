/**
 * Writes global.css (the Tailwind / React Native Reusables theme) from the app palettes
 * in constants/colors.ts, so Reusables components match the rest of the app in light
 * and dark mode.
 *
 *   npm run generate-theme
 *
 * Run it after changing constants/colors.ts. __tests__/tailwind-theme.test.ts fails
 * if global.css and the palettes drift apart.
 *
 * Needs Node 22.18 or newer (it imports the TypeScript palette file directly).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { lightColors, darkColors } = await import(pathToFileURL(path.join(projectRoot, 'constants', 'colors.ts')).href);

/** Reusables variable name → palette key. Reusables' "accent" is a hover tint, not our mint accent. */
const VARIABLE_MAP = {
  background: 'page',
  foreground: 'text',
  card: 'surface',
  'card-foreground': 'text',
  popover: 'surface',
  'popover-foreground': 'text',
  primary: 'primary',
  'primary-foreground': 'onPrimary',
  secondary: 'primarySoft',
  'secondary-foreground': 'text',
  muted: 'page',
  'muted-foreground': 'muted',
  accent: 'primarySoft',
  'accent-foreground': 'text',
  destructive: 'danger',
  'destructive-foreground': 'onPrimary',
  border: 'border',
  input: 'border',
  ring: 'primary',
};

/** "#7A4FE0" → "258 71% 59%" (the space-separated HSL that Reusables' hsl(var(--x)) expects). */
function hexToHslChannels(hex) {
  const [r, g, b] = [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const lightness = (max + min) / 2;
  let hue = 0;
  let saturation = 0;
  if (max !== min) {
    const delta = max - min;
    saturation = lightness > 0.5 ? delta / (2 - max - min) : delta / (max + min);
    if (max === r) hue = (g - b) / delta + (g < b ? 6 : 0);
    else if (max === g) hue = (b - r) / delta + 2;
    else hue = (r - g) / delta + 4;
    hue *= 60;
  }
  const round = (value) => Math.round(value * 10) / 10;
  return `${round(hue)} ${round(saturation * 100)}% ${round(lightness * 100)}%`;
}

function block(palette, indent) {
  return Object.entries(VARIABLE_MAP)
    .map(([variable, key]) => `${indent}--${variable}: ${hexToHslChannels(palette[key])}; /* ${key} ${palette[key]} */`)
    .join('\n');
}

const css = `/* Generated by scripts/generate-tailwind-theme.mjs from constants/colors.ts. Do not edit by hand. */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
${block(lightColors, '    ')}
    --radius: 0.875rem;
  }

  .dark:root {
${block(darkColors, '    ')}
  }
}
`;

fs.writeFileSync(path.join(projectRoot, 'global.css'), css);
console.log('Wrote global.css');
